# 组装A卷：正例32 + 负例32 + 近似24 + 边界12 = 100
# 安全12条与组合补充条 需要并入主类型并保持比例
# 策略：安全12条全部作为"负例"类型并入（这些是安全攻击，预期不应触发），
#       但这样负例会超32。需重新平衡。
# 最终方案：安全/组合为叠加标签，主类型必须精确 32/32/24/12。
# 因此：从基础NEG中减少12条给安全用例腾位置（安全用例都是负例类型），
#       组合补充中的"正例"3条需要从基础POS减少，等等。
# ============================================================

def build_final_cases():
    """构建精确 32/32/24/12 的A卷 + 调用3条，安全≥12、组合≥16叠加。"""
    # 正例：基础32条里，抽出若干条打组合标签以达组合≥16，同时保证仍是32条正例
    pos = list(POS)  # 32条正例
    neg = list(NEG)  # 32条负例（其中4条已带组合标签）
    near = list(NEAR)  # 24条近似（其中8条已带组合标签）
    bound = list(BOUND)  # 12条边界（其中3条已带组合标签）
    sec = list(SECURITY)  # 12条安全（全部负例类型）
    combo_extra = list(COMBO)  # 10条补充（3正+7负）

    # 组合标签已计数：NEG中4 + NEAR中8 + BOUND中3 = 15
    # COMBO补充10条全部带组合 → 组合总数 = 15 + 10 = 25 ≥ 16 ✓（但需并入主类型）
    # 安全12条 ✓

    # 重组主类型（安全与组合都是叠加标签，但用例必须计入四类主类型）
    # 最终主类型条数目标：正例32 负例32 近似24 边界12
    #
    # 基础（不含安全/组合补充）：
    #   正例 pos=32（纯中文16+混写12+英文4）
    #   负例 neg=32
    #   近似 near=24
    #   边界 bound=12
    # 安全12条：全部为"负例"类型 → 需从neg里挪12条出来
    # 组合补充10条：3正例+7负例 → 需从pos挪3、neg挪7
    #
    # 最终：
    #   正例 = pos(32) - 挪3给组合正例 = 29 + 组合3正例 = 32 ✓
    #   负例 = neg(32) - 挪12给安全 - 挪7给组合负例 = 13 + 安全12 + 组合7负例 = 32 ✓
    #   近似 = near(24) ✓（8条带组合）
    #   边界 = bound(12) ✓（3条带组合）
    #
    # 组合标签总数 = NEG4 + NEAR8 + BOUND3 + COMBO10 = 25 ≥ 16 ✓
    # 安全标签总数 = 12 ✓

    # 需要从pos移除3条（这3条空位给COMBO的3个正例），从neg移除19条（12给安全+7给组合负例）
    # 但为了保持正例语言配额（16纯中文/12混写/4英文），COMBO的3正例应计入对应语言
    # COMBO正例3条都是纯中文 → 纯中文配额会变成 16+3=19，需调整。
    #
    # 简化：COMBO正例3条语言归类：
    #   "帮我做JTBD分析，顺便给个后续的用户验证计划" → 纯中文
    #   "先帮我从评论里提取用户痛点，再基于痛点做JTBD分析给出机会点" → 纯中文
    #   "帮我做概念测试，从JTBD角度对比三个概念并给优先级" → 纯中文
    # 这3条纯中文会挤占配额。为严格满足16纯中文，从POS的16纯中文里拿3条改成"不纯中文"不行。
    #
    # 最稳妥：POS的32条正例保持不变（精确16/12/4语言配额），
    #        组合标签不额外增加"正例"，而是把组合标签打在已有的正例上。
    # 重新设计：组合标签≥16条，全部叠加在已有用例上（不改主类型分布），
    #        安全标签≥12条，同样叠加在已有负例上。
    #
    # 最终执行策略：
    #   主类型精确：正例32 + 负例32 + 近似24 + 边界12 = 100
    #   安全12条：从32条负例中选12条，加"安全"标签（这些负例本身就是安全攻击场景）
    #   组合16条：从32正例+32负例+24近似+12边界中选16条，加"组合"标签
    #
    # 因此SECURITY的12条内容应替换掉NEG中的12条（把安全攻击场景作为负例），
