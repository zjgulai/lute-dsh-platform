    # 重建负例：取NEG前20条 + SECURITY 12条 = 32条负例（其中12条带安全标签）
    neg_final = list(NEG[:20]) + list(SECURITY)  # 20 + 12 = 32 ✓

    # 组合标签：从各主类型中选16条打组合标签
    # 正例中打4条组合、负例中打4条组合、近似中打6条组合、边界中打2条组合 = 16 ✓
    combo_tagged_ids = set()

