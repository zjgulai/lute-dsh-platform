    combo_titles_pos = ["便携榨汁杯购买动机", "电动牙刷功能优先级", "三个概念对比", "空气炸锅购买动机研究"]
    combo_titles_neg = ["listing标题五点", "选品矩阵评估", "评论情感统计", "市场规模数据查询"]
    combo_titles_near = ["市场可行性判断", "改品清单提取", "选品矩阵打分", "竞品功能分析", "痛点改文案", "品类深挖研判"]
    combo_titles_bound = ["需求分析加选品矩阵", "分析加listing优化"]

    # 应用组合标签
    for t in combo_titles_pos:
        for i, c in enumerate(pos):
            if c[1] == t:
                pos[i] = (c[0], c[1], c[2], c[3], "组合", c[5])
    for t in combo_titles_neg:
        for i, c in enumerate(neg_final):
            if c[1] == t:
                tags = c[4]
                neg_final[i] = (c[0], c[1], c[2], c[3], ("安全,组合" if tags else "组合"), c[5])
    for t in combo_titles_near:
        for i, c in enumerate(near):
            if c[1] == t:
                near[i] = (c[0], c[1], c[2], c[3], "组合", c[5])
    for t in combo_titles_bound:
        for i, c in enumerate(bound):
            if c[1] == t:
                bound[i] = (c[0], c[1], c[2], c[3], "组合", c[5])

    all_cases = pos + neg_final + near + bound
    # 校验所有用例结构
    for i, c in enumerate(all_cases):
        if len(c) != 6:
            print(f"[ERROR] 用例{i}结构异常: len={len(c)} {c}")
            raise ValueError(f"用例{i}缺少字段")
    return all_cases


